/* Ключ пары фракций.

   Отношение между двумя фракциями хранится один раз на пару, поэтому ключ должен быть одинаковым
   при любом порядке аргументов: pairKey(2, 0) и pairKey(0, 2) дают одну строку «0|2».
   Такую же строку использует и рисование границ, поэтому вынесено в общий модуль. */

export const pairKey = (a, b) => (a < b ? `${a}|${b}` : `${b}|${a}`);
