/* Культуры фракций.

   У каждой фракции есть культура — семь доступных вариантов, каждый со своим цветом. Культура
   задаёт «характер» фракции: цвет её армий и границ, а также склонности (агрессия, торговля,
   любовь к эфиру), которыми пользуется ИИ. Всё вынесено в константы: цвета, названия и склонности
   можно менять здесь, не трогая код игры. */

/* Название -> цвет. Семь цветов по числу культур; порядок совпадает с порядком культуры у фракции,
   поэтому синяя культура — первая, фиолетовая — последняя. */
export const CULTURE_NAMES = Object.freeze(['Синяя', 'Чёрная', 'Зелёная', 'Красная', 'Белая', 'Жёлтая', 'Фиолетовая']);

export const CULTURE_COLORS = Object.freeze([
    '#3d6ea8', // синяя
    '#2b2b33', // чёрная
    '#4f8f52', // зелёная
    '#c0503a', // красная
    '#d9d2c0', // белая
    '#c8a53a', // жёлтая
    '#7a4f9c'  // фиолетовая
]);

/* Склонности культуры — ими управляется ИИ (см. src/game/ai.js).
   aggression 0..1 — как охотно культура нападает и расширяется силой;
   trade      0..1 — как охотно улучшает отношения и заключает союзы;
   ether      0..1 — интерес к землям эфира (перевешивает обычную выгоду). */
export const CULTURES = Object.freeze(CULTURE_NAMES.map((name, id) => Object.freeze({
    id,
    name,
    color: CULTURE_COLORS[id],
    aggression: [0.3, 0.8, 0.35, 1.0, 0.25, 0.45, 0.6][id],
    trade: [0.7, 0.2, 0.6, 0.3, 0.8, 0.55, 0.4][id],
    ether: [0.4, 0.5, 0.5, 0.3, 0.5, 0.4, 1.0][id]
})));

// Культура по индексу (с заворотом) — удобно для фракций и отрисовки.
export function cultureById(id) {
    if (CULTURES.length === 0) return null;
    return CULTURES[((id % CULTURES.length) + CULTURES.length) % CULTURES.length];
}
